/**
 * @file    chapter.h
 * @brief   主实验控制模块头文件
 * @details 提供统一的模块初始化和实验入口
 */

#ifndef __CHAPTER_H
#define __CHAPTER_H

#include <stdint.h>

/* ==================== 全局变量 ==================== */
/**
 * @brief  全局输出使能标志
 * @note   1 = 所有模块开启，0 = 所有模块关闭（按键中断控制）
 */
extern volatile uint8_t outputs_requested_on;

/* ==================== 核心函数 ==================== */
/**
 * @brief  Chapter 主函数：初始化所有模块
 * @param  None
 * @retval None
 * @note   在 main() 中调用一次
 */
void chapter_main(void);

/**
 * @brief  按键中断回调：翻转所有模块开关状态
 * @param  None
 * @retval None
 * @note   在 HAL_GPIO_EXTI_Callback 中调用
 */
void Chapter_ToggleOutputsFromISR(void);

/** Configure PA0 as the active-low user-button EXTI input. */
void Chapter_UserKeyInterruptInit(void);

/** Return and clear a debounced task-1 start request generated by EXTI0. */
uint8_t Chapter_ConsumeHCourseStartRequest(void);

#endif /* __CHAPTER_H */
